#!/usr/bin/env node
/**
 * generate-components-catalog.mjs — scans the component stylesheets and emits
 * COMPONENTS.md: every component, its CSS classes (block / __element / --modifier)
 * and the design tokens each stylesheet references. Lets a human or an LLM use the
 * class API without reading the CSS.
 *
 * Run: pnpm --filter @lmthing/css catalog   (or: node scripts/generate-components-catalog.mjs)
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const SRC = join(root, 'src');

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (name.endsWith('.css') && name !== 'theme.css') out.push(p);
  }
  return out;
}

// Color-token names (without the -- prefix) from the generated manifest.
const manifest = JSON.parse(readFileSync(join(root, 'tokens.manifest.json'), 'utf8'));
const COLOR_TOKENS = new Set(manifest.colors.map((c) => c.name));

const CLASS_RE = /\.(-?[a-zA-Z][\w-]*)/g;
const VAR_RE = /var\(\s*(--[\w-]+)/g;
const UTIL_RE = /@apply[^;]*/g;
const UTIL_COLOR_RE = /\b(?:bg|text|border|ring|from|via|to|fill|stroke)-([a-z][\w-]*)/g;

function analyze(file) {
  // Drop at-rule reference/import lines so paths like "theme.css" aren't read as classes.
  const css = readFileSync(file, 'utf8')
    .split('\n')
    .filter((l) => !/^\s*@(reference|import|source)\b/.test(l))
    .join('\n');
  const classes = new Set();
  let m;
  CLASS_RE.lastIndex = 0;
  while ((m = CLASS_RE.exec(css))) classes.add(m[1]);
  const tokens = new Set();
  VAR_RE.lastIndex = 0;
  while ((m = VAR_RE.exec(css))) tokens.add(m[1]);
  // token utilities used via @apply (bg-primary, text-agent, …)
  UTIL_RE.lastIndex = 0;
  let a;
  while ((a = UTIL_RE.exec(css))) {
    UTIL_COLOR_RE.lastIndex = 0;
    let u;
    while ((u = UTIL_COLOR_RE.exec(a[0]))) {
      const name = u[1].replace(/\/.*$/, '');
      if (COLOR_TOKENS.has(name)) tokens.add(name);
    }
  }
  // group classes by their base block (before __ or --)
  const blocks = {};
  for (const c of [...classes].sort()) {
    const base = c.split(/__|--/)[0];
    (blocks[base] ||= []).push(c);
  }
  return { blocks, tokens: [...tokens].sort() };
}

const files = [...walk(join(SRC, 'elements')), ...walk(join(SRC, 'components'))];
let md = `# Component catalog\n\n`;
md += `_Generated by \`scripts/generate-components-catalog.mjs\` from \`src/{elements,components}/**\`. Do not hand-edit._\n\n`;
md += `Import a component's stylesheet with \`import '@lmthing/css/<path>'\` and use its classes. All colors resolve to design tokens — see [DESIGN.md](./DESIGN.md) and [tokens.manifest.json](./tokens.manifest.json).\n\n`;

let group = '';
for (const file of files) {
  const rel = relative(SRC, file);
  const section = rel.startsWith('elements') ? 'Elements (primitives)' : 'Components (features)';
  if (section !== group) {
    group = section;
    md += `\n## ${section}\n`;
  }
  const { blocks, tokens } = analyze(file);
  md += `\n### \`${rel}\`\n\n`;
  for (const [base, cls] of Object.entries(blocks)) {
    md += `- **.${base}** — ${cls.map((c) => `\`.${c}\``).join(' ')}\n`;
  }
  if (tokens.length) md += `\n  Tokens: ${tokens.map((t) => `\`${t}\``).join(', ')}\n`;
}

writeFileSync(join(root, 'COMPONENTS.md'), md);
console.log(`[catalog] wrote COMPONENTS.md (${files.length} stylesheets)`);
